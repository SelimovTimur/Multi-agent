// Подсказка живого разговора собирается из двух частей (live.js,
// liveReviewHint): первая — одна из строк выше, вторая — без обращения.
const LIVE_TAIL = ' Если ничего не нажимать, через 20 секунд текст уйдёт как есть.'
const LIVE_SHORT = ['Проверь, правильно ли мы тебя услышали.', 'Проверьте, правильно ли мы вас услышали.']

/** polite — строка для учителя: вежливая пара или та же строка. */
export function polite(text, formal = true) {
	if (!formal || typeof text !== 'string') return text
	const pair = FORMAL.get(text)
	if (pair) return pair
	if (text.endsWith(LIVE_TAIL)) {
		const head = text.slice(0, -LIVE_TAIL.length)
		if (head === LIVE_SHORT[0]) return LIVE_SHORT[1] + LIVE_TAIL
		const headPair = FORMAL.get(head)
		if (headPair) return headPair + LIVE_TAIL
	}
	return text
}

/** usePolite — функция подмены строк для текущего экрана. */
export function usePolite() {
	const formal = useContext(FormalContext)
	return useCallback((text) => polite(text, formal), [formal])
}

/** useFormal — экран смотрит учитель. */
export function useFormal() {
	return useContext(FormalContext)
}

