package learning

import "testing"

func TestToTatarCyrillic(t *testing.T) {
	cases := []struct{ name, in, want string }{
		{"татарский текст не меняется", "Җәй көне һава җылы, ә мин өйдә утырам.", "Җәй көне һава җылы, ә мин өйдә утырам."},
		{"казахские и башкирские буквы", "Тағы бір рет айт, ҡыҙ ҪУ", "Тагы бер рет айт, кыз СУ"},
		{"латиница внутри кириллического слова", "Mәктәп hәм мәктәпtә", "Мәктәп һәм мәктәптә"},
		{"слово тюркской латиницей", "Мин mäktäptä укыйм", "Мин мәктәптә укыйм"},
		{"реплика латиницей", "Anlamadım, İdel", "Анламадым, Идел"},
		{"турецкая реплика", "Bilmeyim", "Билмейим"},
		{"диграфы и э в начале слова", "eş yaxşı", "эш яхшы"},
		{"латинское имя в кириллической реплике", "Мин YouTube карыйм", "Мин YouTube карыйм"},
		{"русский и цифры", "Привет! 15 минут.", "Привет! 15 минут."},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := toTatarCyrillic(tc.in); got != tc.want {
				t.Fatalf("toTatarCyrillic(%q) = %q, want %q", tc.in, got, tc.want)
			}
		})
	}
}
