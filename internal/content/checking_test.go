package content

import "testing"

// Сравнение ответов — то место, где строгость обиднее всего: ученик
// ответил верно, а ему засчитали ошибку из-за пробела.
func TestSameAnswer(t *testing.T) {
	same := []struct{ expected, got, why string }{
		{"эчпочмак", "эчпочмак", "точное совпадение"},
		{"Эчпочмак", "эчпочмак", "регистр не решает"},
		{"эчпочмак", "  эчпочмак  ", "пробелы по краям"},
		{"татар халкының милли ризыгы", "татар  халкының   милли ризыгы", "двойные пробелы внутри"},
		{"A", "a", "идентификатор варианта в другом регистре"},
	}
	for _, c := range same {
		if !sameAnswer(c.expected, c.got) {
			t.Errorf("%s: %q и %q должны считаться одинаковыми", c.why, c.expected, c.got)
		}
	}

	different := []struct{ expected, got, why string }{
		{"A", "B", "другой вариант"},
		{"эчпочмак", "чәкчәк", "другое слово"},
		{"эчпочмак", "", "пустой ответ не верен"},
		{"эчпочмак", "эчпочмаклар", "другая форма слова — это другой ответ"},
	}
	for _, c := range different {
		if sameAnswer(c.expected, c.got) {
			t.Errorf("%s: %q и %q не должны совпадать", c.why, c.expected, c.got)
		}
	}
}
